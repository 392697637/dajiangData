-- 接口：GET /api/airspace/blocks/{block_id}/plans
-- 用途：根据空域区块ID和使用日期查询该区块下的用空计划数组。
--
--  查询用空计划前端请求参数
-- 参数：
--   block_id       bigint    必填，空域区块主键
--   use_date       date      必填，使用日期，格式：YYYY-MM-DD
